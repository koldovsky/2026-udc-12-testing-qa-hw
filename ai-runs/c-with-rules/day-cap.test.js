// Unit-тести для app/src/day-cap.js (createDayCap, dayKey).
//
// Джерело очікувань. Файлу docs/spec/tariffs.md у робочій теці немає, тож номери рядків
// специфікації не перевірені й не вказані. Ліміт 300 грн і правило «день — за київським
// часом» для T6 взято з правил проєкту (CLAUDE.md, правила 8 і 9). Очікування — літерали.

import { test } from "node:test";
import assert from "node:assert/strict";

import { createDayCap, dayKey } from "../../app/src/day-cap.js";

// T6: ліміт 300 грн = 30 000 коп.
// Впаде, якщо: DAY_CAP ≠ 30 000.
test("T6: новий журнал — залишок 30000 коп.", () => {
  const cap = createDayCap();
  assert.equal(cap.remaining("r1", "2026-09-16T12:00:00+03:00"), 30000);
});

// T6: 30 000 − 12 000 = 18 000.
// Впаде, якщо: record не накопичує суму; remaining не віднімає записане.
test("T6: після 12000 коп. залишок 18000", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T09:00:00+03:00", 12000);
  assert.equal(cap.remaining("r1", "2026-09-16T18:00:00+03:00"), 18000);
});

// T6: записи того самого дня додаються: 10 000 + 15 000 = 25 000 → залишок 5 000.
// Впаде, якщо: record перезаписує, а не додає.
test("T6: два записи за день складаються → залишок 5000", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T09:00:00+03:00", 10000);
  cap.record("r1", "2026-09-16T13:00:00+03:00", 15000);
  assert.equal(cap.remaining("r1", "2026-09-16T18:00:00+03:00"), 5000);
});

// T6: залишок не буває від'ємним: 30 000 − 35 000 → 0.
// Впаде, якщо: прибрати Math.max(0, …).
test("T6: перевищення ліміту → залишок 0, не від'ємний", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T09:00:00+03:00", 35000);
  assert.equal(cap.remaining("r1", "2026-09-16T18:00:00+03:00"), 0);
});

// T6: ліміт — на кожного користувача окремо.
// Впаде, якщо: ключ журналу не містить riderId.
test("T6: записи r1 не зменшують ліміт r2", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T09:00:00+03:00", 30000);
  assert.equal(cap.remaining("r2", "2026-09-16T18:00:00+03:00"), 30000);
});

// T6: ліміт — на день; наступного дня знову 30 000.
// Впаде, якщо: ключ журналу не містить дату.
test("T6: наступного дня ліміт знову 30000", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T12:00:00+03:00", 30000);
  assert.equal(cap.remaining("r1", "2026-09-17T12:00:00+03:00"), 30000);
});

// T6 за Києвом, межа 23:59 / 00:00 (+03:00). 23:30 16.09 і 00:30 17.09 за Києвом — різні дні,
// хоча в UTC обидва моменти — 16.09 (20:30Z і 21:30Z).
// Впаде, якщо: день береться в UTC.
test("T6: 23:30 і 00:30 за Києвом (+03:00) — різні дні ліміту", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-16T23:30:00+03:00", 30000);
  assert.equal(cap.remaining("r1", "2026-09-17T00:30:00+03:00"), 30000);
});

// T6 за Києвом: 01:00 і 12:00 17.09 за Києвом — той самий день, хоча в UTC це 16.09 22:00Z
// і 17.09 09:00Z. 30 000 − 20 000 = 10 000.
// Впаде, якщо: день береться в UTC (тоді 30 000).
test("T6: 01:00 і 12:00 за Києвом (+03:00) — один день ліміту → залишок 10000", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-17T01:00:00+03:00", 20000);
  assert.equal(cap.remaining("r1", "2026-09-17T12:00:00+03:00"), 10000);
});

// T6 за Києвом, зимовий час (+02:00): 01:00 11.11 Київ = 23:00Z 10.11.
// Впаде, якщо: день береться в UTC або зсув Києва захардкоджено як +03:00.
test("T6: 01:00 і 12:00 за Києвом (+02:00) — один день ліміту → залишок 10000", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-11-11T01:00:00+02:00", 20000);
  assert.equal(cap.remaining("r1", "2026-11-11T12:00:00+02:00"), 10000);
});

// chargedOn повертає суму за київський день.
// Впаде, якщо: запис ведеться за UTC-датою (тоді 17.09 → 0).
test("T6: chargedOn('2026-09-17') бачить поїздку о 01:00 за Києвом", () => {
  const cap = createDayCap();
  cap.record("r1", "2026-09-17T01:00:00+03:00", 20000);
  assert.equal(cap.chargedOn("r1", "2026-09-17"), 20000);
});

// chargedOn для дня без поїздок — 0.
// Впаде, якщо: повертає undefined.
test("T6: chargedOn для дня без поїздок → 0", () => {
  const cap = createDayCap();
  assert.equal(cap.chargedOn("r1", "2026-09-17"), 0);
});

// dayKey — дата за Києвом.
// Впаде, якщо: dayKey повертає UTC-дату.
test("T6: dayKey('2026-09-17T00:30:00+03:00') → '2026-09-17'", () => {
  assert.equal(dayKey("2026-09-17T00:30:00+03:00"), "2026-09-17");
});

// dayKey: 23:59 за Києвом — ще поточний день.
// Впаде, якщо: dayKey зсуває дату вперед.
test("T6: dayKey('2026-09-16T23:59:00+03:00') → '2026-09-16'", () => {
  assert.equal(dayKey("2026-09-16T23:59:00+03:00"), "2026-09-16");
});

// Власний ліміт через параметр.
// Впаде, якщо: параметр limit ігнорується.
test("createDayCap({ limit: 10000 }) — залишок 10000, після 4000 → 6000", () => {
  const cap = createDayCap({ limit: 10000 });
  assert.equal(cap.limit, 10000, "limit");
  assert.equal(cap.remaining("r1", "2026-09-16T12:00:00+03:00"), 10000, "залишок до записів");
  cap.record("r1", "2026-09-16T12:00:00+03:00", 4000);
  assert.equal(cap.remaining("r1", "2026-09-16T13:00:00+03:00"), 6000, "залишок після 4000");
});
