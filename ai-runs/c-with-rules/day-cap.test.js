// Unit-тести журналу денного ліміту — app/src/day-cap.js.
//
// Звідки очікуване. Специфікацію docs/spec/tariffs.md у цьому завданні читати не можна, а з коду
// й коментарів у ньому очікуване брати не можна (CLAUDE.md, правила 1–2). Тож тут лише те, що
// випливає із самого поняття «денний ліміт» (CLAUDE.md: «денний ліміт»; правило 10: record(…)
// записує, «скільки вже нараховано за добу»):
//   • поки за добу нічого не нараховано, доступний увесь ліміт;
//   • нараховане за добу підсумовується й на стільки ж зменшує залишок цієї доби;
//   • наступна доба починається з повного ліміту.
// Розмір ліміту визначає специфікація, тому кожен тест задає свій — 1000 коп. — і не спирається
// на DAY_CAP. Моменти — день за Києвом (+03:00, до переходу на зимовий час 25.10.2026): київська
// й UTC-дата тут однакові, тож тести НЕ вирішують відкритого питання, за чиїм часом рахується
// доба. Його та інші відкриті випадки (перевитрата ліміту, окремий ліміт на кожного райдера) не
// закріплено — вони винесені як питання до власника продукту.

import { test } from "node:test";
import assert from "node:assert/strict";
import { createDayCap } from "../../app/src/day-cap.js";

const OCT_1_MORNING = "2026-10-01T10:00:00+03:00"; // = 2026-10-01T07:00:00Z, дата та сама
const OCT_1_EVENING = "2026-10-01T18:00:00+03:00"; // = 2026-10-01T15:00:00Z, дата та сама
const OCT_2_MORNING = "2026-10-02T10:00:00+03:00"; // = 2026-10-02T07:00:00Z, дата та сама

test("денний ліміт: за добу ще нічого не нараховано — доступний увесь ліміт", () => {
  const dayCap = createDayCap({ limit: 1000 }); // за 01.10 нараховано 0
  // 1000 − 0 = 1000
  assert.equal(dayCap.remaining("rider-1", OCT_1_MORNING), 1000);
});

test("денний ліміт: за добу ще нічого не нараховано — нараховане дорівнює 0", () => {
  const dayCap = createDayCap({ limit: 1000 }); // за 01.10 нараховано 0
  assert.equal(dayCap.chargedOn("rider-1", "2026-10-01"), 0);
});

test("денний ліміт: нараховане за добу зменшує залишок цієї доби", () => {
  const dayCap = createDayCap({ limit: 1000 });
  dayCap.record("rider-1", OCT_1_MORNING, 300); // за 01.10 нараховано 300
  // 1000 − 300 = 700
  assert.equal(dayCap.remaining("rider-1", OCT_1_EVENING), 700);
});

test("денний ліміт: нарахування за одну добу підсумовуються", () => {
  const dayCap = createDayCap({ limit: 1000 });
  dayCap.record("rider-1", OCT_1_MORNING, 300);
  dayCap.record("rider-1", OCT_1_EVENING, 450);
  // 300 + 450 = 750
  assert.equal(dayCap.chargedOn("rider-1", "2026-10-01"), 750);
});

// Межа «нараховано рівно ліміт». Крок за нею (нараховано 1001 при ліміті 1000) не перевіряю:
// залишок там 0 чи −1 — відкрите питання.
test("денний ліміт: за добу нараховано рівно ліміт — залишок 0", () => {
  const dayCap = createDayCap({ limit: 1000 });
  dayCap.record("rider-1", OCT_1_MORNING, 1000); // за 01.10 нараховано 1000
  // 1000 − 1000 = 0
  assert.equal(dayCap.remaining("rider-1", OCT_1_EVENING), 0);
});

test("денний ліміт: наступна доба починається з повного ліміту", () => {
  const dayCap = createDayCap({ limit: 1000 });
  dayCap.record("rider-1", OCT_1_MORNING, 1000); // 01.10 ліміт вичерпано; за 02.10 нараховано 0
  // 1000 − 0 = 1000
  assert.equal(dayCap.remaining("rider-1", OCT_2_MORNING), 1000);
});
