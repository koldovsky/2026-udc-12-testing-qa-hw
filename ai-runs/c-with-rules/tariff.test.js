// Unit-тести тарифу — app/src/tariff.js.
//
// Звідки очікуване. Ставки, блоки, безкоштовні хвилини, знижки, нічне вікно, розмір денного
// ліміту, збори та їхні межі визначає docs/spec/tariffs.md, а його в цьому завданні читати не
// можна. Брати ці числа з коду (RATES, DAY_CAP, …) чи з коментарів у ньому не можна (CLAUDE.md,
// правила 1–3), тож тестів на конкретні ціни тут немає: ці випадки винесені як питання до
// власника продукту. Тут лише те, що не залежить від чисел тарифу.

import { test } from "node:test";
import assert from "node:assert/strict";
import { createDayCap } from "../../app/src/day-cap.js";
import { discount, quote } from "../../app/src/tariff.js";

// CLAUDE.md: «Гроші — цілі копійки». Точний відсоток від цих сум — дріб, тож знижку треба
// округлити. У який бік — відкрите питання (специфікація недоступна), тому перевіряю лише, що
// знижка — ціла кількість копійок, а не саме її значення.
const FRACTIONAL_PERCENT_CASES = [
  { amount: 1005, percent: 30 }, // 1005 × 30 / 100 = 301,5
  { amount: 333, percent: 50 }, //   333 × 50 / 100 = 166,5
  { amount: 999, percent: 20 }, //   999 × 20 / 100 = 199,8
];

for (const { amount, percent } of FRACTIONAL_PERCENT_CASES) {
  test(`гроші — цілі копійки: знижка ${percent} % від ${amount} коп. — ціле число копійок`, () => {
    assert.equal(Number.isInteger(discount(amount, percent)), true);
  });
}

// Денний ліміт через quote. Коли за добу вже нараховано весь ліміт, поїздка того ж дня не може
// нічого додати до нарахованого за цю добу, бо інакше ліміт перевищено. Очікуване не залежить
// від ставок: хай якою буде ціна поїздки, нараховане лишається на рівні ліміту.
//   ліміт — свій, 1000 коп. (не DAY_CAP); райдер — звичайний;
//   zones — дублер «повернення в зоні» (замінено лише залежність, quote і createDayCap — справжні);
//   поїздка 01.10 12:00–13:00 за Києвом (= 09:00–10:00Z): київська й UTC-дата однакові, тож тест
//   не вирішує відкритого питання, за чиїм часом рахується доба.
const IN_ZONE = { zoneOf: () => "in" };

test("денний ліміт вичерпано: поїздка того ж дня не збільшує нараховане за добу", () => {
  const dayCap = createDayCap({ limit: 1000 });
  dayCap.record("rider-1", "2026-10-01T09:00:00+03:00", 1000); // за 01.10 уже нараховано 1000
  quote(
    {
      pickupAt: "2026-10-01T12:00:00+03:00",
      returnAt: "2026-10-01T13:00:00+03:00",
      bike: "classic",
      returnStation: "TEST-IN",
    },
    { type: "standard", id: "rider-1" },
    { zones: IN_ZONE, dayCap },
  );
  // 1000 (уже нараховано) + 0 (понад ліміт нараховувати нічого) = 1000
  assert.equal(dayCap.chargedOn("rider-1", "2026-10-01"), 1000);
});
